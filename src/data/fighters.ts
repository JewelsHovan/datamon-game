// Playable fighters (spec 006, spec 016): archetype, two signature specials, per-fighter
// physics/offense/defense modifiers, cancel chain trait, passive trait, signature battlemon,
// SFX pitch identity and Compass-friendly win quote.
// Pure data: src/sim reads integer modifiers; menus, audio and effects read labels/flavor.
import type { MoveId } from "./moves";

export type Archetype = "all-rounder" | "rusher" | "bruiser" | "zoner" | "trickster";

/**
 * Archetype normal-cancel routing:
 * - "standard": default MOVES[id].cancels (LP -> HP/HK/Special, LK -> HK/Special, HP -> Special)
 * - "rush-chain": LP also chains into LK and crouch_attack; crouch_attack cancels into Special
 * - "heavy-cancel": HK and crouch_attack also cancel into Special on hit/block
 * - "poke-cancel": LK and crouch_attack cancel into Special; LP chains into LK
 */
export type ChainTrait = "standard" | "rush-chain" | "heavy-cancel" | "poke-cancel";

export interface FighterInfo {
  slug: string;
  archetype: Archetype;
  archetypeLabel: string;
  /** Neutral Special (Special button). */
  specialMove: MoveId;
  specialName: string;
  /** Directional Special (Forward + Special). */
  altSpecialMove: MoveId;
  altSpecialName: string;
  /** Short passive identity shown on Select / Versus. */
  traitName: string;
  traitDesc: string;
  /** Signature Battlemon slug from datamonCatalog. */
  battlemonSlug: string;
  /** Friendly Compass work-themed win quote shown on Results. */
  winQuote: string;
  /** Subtle WebAudio pitch multiplier for attacks/taunts (e.g. 0.90 .. 1.12). */
  sfxPitch: number;

  // --- Deterministic integer sim modifiers (baseline = 100 / 0 / 6) ---
  /** Health per round (all-rounder baseline 1000). */
  health: number;
  /** Damage dealt, in percent of the move's base damage. */
  damagePct: number;
  /** Walk speed, in percent of MOVEMENT.walkForwardSpeed / walkBackSpeed. */
  walkPct: number;
  /** Forward and back dash speed, in percent of MOVES_V2.dashForwardSpeed / dashBackSpeed. */
  dashSpeedPct: number;
  /** Invulnerable startup frames on backdash (baseline MOVES_V2.dashBackInvuln = 6). */
  dashBackInvuln: number;
  /** Upward jump launch speed percent (baseline 100). */
  jumpVyPct: number;
  /** Horizontal jump travel speed percent (baseline 100). */
  jumpVxPct: number;
  /** Even integer offset added to MOVEMENT.gravity (must be even so >> 1 is exact; baseline 0). */
  gravityOffset: number;
  /** Normal throw range in percent of COMBAT.throwRange (baseline 100). */
  throwRangePct: number;
  /** Normal throw damage in percent of MOVES.throw.damage (baseline 100). */
  throwDamagePct: number;
  /** Pushback inflicted on defender in percent of move.push (baseline 100). */
  pushbackPct: number;
  /** Percent reduction of chip damage taken while blocking specials (0..60; baseline 0). */
  chipResistPct: number;
  /** Minimum combo damage scaling floor (baseline COMBAT.comboScaleFloor = 50). */
  comboFloorPct: number;
  /** Normal cancel routing flavor. */
  chainTrait: ChainTrait;
}

